#include <stdio.h>

int main(void)
{
    double x, y;

    /* Контрольные примеры:
       (-2, 1) — принадлежит;
       (2, 1) — принадлежит;
       (-3, 0), (0, 3), (6, 0) — принадлежат (граница);
       (-3, 1), (4, 2), (0, -1) — не принадлежат.
    */

    printf("Введите x и y: ");
    scanf("%lf %lf", &x, &y);

    if (y >= 0 &&
        ((x <= 0 && x * x + y * y <= 9) ||
         (x >= 0 && x + 2 * y <= 6)))
    {
        printf("Точка принадлежит области\n");
    }
    else
    {
        printf("Точка не принадлежит области\n");
    }

    return 0;
}
